"""Generate `notebooks/02_one_shot_pipeline.ipynb` from the project source.

The Colab notebook must run without cloning this repository, and the repository
must stay the single source of truth. This generator resolves that by embedding
the project modules in one notebook cell: the cell writes them into a scratch
directory and puts that directory at the front of `sys.path`, so the notebook
imports exactly the same code as the working copy in VS Code.

Usage:
    python tools/embed_sources.py           # rewrite the notebook
    python tools/embed_sources.py --check   # exit 1 if the notebook is stale

The notebook JSON is written directly (no nbformat dependency), so the tool runs
in any environment that can execute the project.
"""


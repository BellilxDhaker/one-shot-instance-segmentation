def write_benchmark_notebook(sources: Dict[str, str], path: Optional[str] = None) -> str:
    path = path or BENCHMARK_NOTEBOOK_PATH
    notebook = build_benchmark_notebook(sources)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        json.dump(notebook, handle, indent=1, ensure_ascii=False)
        handle.write("\n")
    return path


def _notebook_cells(path: Optional[str] = None) -> List[Dict[str, object]]:
    path = path or NOTEBOOK_PATH
    if not os.path.exists(path):
        return []
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle).get("cells", [])


def notebook_has_stored_outputs(path: Optional[str] = None) -> bool:
    """True when the committed notebook carries cell outputs or run counts.

    Executed outputs embed base64 figures, which pushed the file to ~2 MB and
    turned every run into a diff. The repository convention is to commit the
    notebook clean, so the checker treats stored outputs as drift.
    """
    for cell in _notebook_cells(path):
        if cell.get("cell_type") != "code":
            continue
        if cell.get("outputs") or cell.get("execution_count") is not None:
            return True
    return False


def notebook_is_current(sources: Dict[str, str], path: Optional[str] = None) -> bool:
    for cell in _notebook_cells(path):
        text = "".join(cell.get("source", []))
        if "SOURCE_FILES = " in text:
            start = text.index("SOURCE_FILES = ") + len("SOURCE_FILES = ")
            end = text.index("\n\nfor relative", start)
            try:
                embedded = json.loads(text[start:end].strip())
            except json.JSONDecodeError:
                return False
            return embedded == stamp_sources(sources, fingerprint(sources))
    return False


def benchmark_sources() -> Dict[str, str]:
    return read_sources(BENCHMARK_MODULES)


def benchmark_notebook_is_current(sources: Optional[Dict[str, str]] = None,
                                  path: Optional[str] = None) -> bool:
    return notebook_is_current(sources or benchmark_sources(), path or BENCHMARK_NOTEBOOK_PATH)


def main(argv: List[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if a notebook is out of date")
    arguments = parser.parse_args(argv)

    targets = (
        ("notebook", NOTEBOOK_PATH, MODULES),
        ("benchmark", BENCHMARK_NOTEBOOK_PATH, BENCHMARK_MODULES),
    )
    failed = False
    for kind, path, modules in targets:
        relative = os.path.relpath(path, PROJECT_ROOT)
        sources = read_sources(modules)
        if arguments.check:
            if not notebook_is_current(sources, path):
                print(f"{relative} is stale; run: python tools/embed_sources.py")
                failed = True
                continue
            if notebook_has_stored_outputs(path):
                print(
                    f"{relative} carries stored cell outputs and execution counts; "
                    "run: python tools/embed_sources.py to regenerate it clean"
                )
                failed = True
                continue
            print(f"{relative} is up to date ({fingerprint(sources)})")
            continue

        written = write_notebook(sources, path) if kind == "notebook" else write_benchmark_notebook(sources, path)
        size = os.path.getsize(written) / 1024.0
        print(
            f"wrote {os.path.relpath(written, PROJECT_ROOT)} from {len(sources)} modules "
            f"({fingerprint(sources)}, {size:.0f} KB, no stored outputs)"
        )
    return 1 if failed else 0



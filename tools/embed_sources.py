def read_sources(modules: Tuple[str, ...] = MODULES) -> Dict[str, str]:
    sources: Dict[str, str] = {}
    for relative in modules:
        path = os.path.join(PROJECT_ROOT, relative)
        with open(path, "r", encoding="utf-8") as handle:
            sources[relative] = handle.read()
    return sources


def fingerprint(sources: Dict[str, str]) -> str:
    digest = hashlib.sha256()
    for relative in sorted(sources):
        digest.update(relative.encode("utf-8"))
        digest.update(hashlib.sha256(sources[relative].encode("utf-8")).digest())
    return digest.hexdigest()[:16]


REVISION_NAME = "NOTEBOOK_SOURCE_REVISION"
_FUTURE_IMPORT = "from __future__ import annotations"


def stamp_sources(sources: Dict[str, str], revision: str) -> Dict[str, str]:
    """Return the embedded copies with a revision marker in each module.

    The marker is injected here rather than kept in the repository, because it
    would otherwise be part of the hash it reports. It exists so a notebook
    session can tell "the files on disk are current" from "the modules I already
    imported are current": re-running the source cell rewrites the files but
    leaves the old modules in `sys.modules`, and a traceback then mixes line
    numbers from two different versions of the same file.
    """
    stamped: Dict[str, str] = {}
    for relative, source in sources.items():
        lines = source.splitlines()
        for index, line in enumerate(lines):
            if line.strip() == _FUTURE_IMPORT:
                marker = [
                    "",
                    f"{REVISION_NAME} = {revision!r}  # injected by tools/embed_sources.py",
                ]
                lines[index + 1 : index + 1] = marker
                break
        else:
            lines.insert(0, f"{REVISION_NAME} = {revision!r}  # injected by tools/embed_sources.py")
        stamped[relative] = "\n".join(lines) + "\n"
    return stamped


def _markdown(text: str) -> Dict[str, object]:
    return {"cell_type": "markdown", "metadata": {}, "source": text.strip("\n").splitlines(keepends=True)}


def _code(text: str) -> Dict[str, object]:
    return {
        "cell_type": "code",
        "execution_count": None,
        "metadata": {},
        "outputs": [],
        "source": text.strip("\n").splitlines(keepends=True),
    }


def _source_cell(sources: Dict[str, str], revision: str) -> Dict[str, object]:
    payload = json.dumps(stamp_sources(sources, revision), indent=4, sort_keys=True)
    return _code(
        f'''
import os
import sys

BUNDLE_ROOT = "{BUNDLE_ROOT}"
EXPECTED_SOURCE_REVISION = "{revision}"
SOURCE_FILES = {payload}

for relative, source in SOURCE_FILES.items():
    path = os.path.join(BUNDLE_ROOT, relative)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write(source)

sys.path.insert(0, os.path.abspath(BUNDLE_ROOT))
print(f"wrote {{len(SOURCE_FILES)}} modules into {{os.path.abspath(BUNDLE_ROOT)}} (revision {{EXPECTED_SOURCE_REVISION}})")
'''
    )


def _revision_check_cell(checked: Tuple[str, ...] = PIPELINE_CHECKED) -> Dict[str, object]:
    """Cell that reloads any module imported from an older embedded revision.

    The reload list is passed in because notebook 03 bundles the Phase 2
    modules too; the cell body is identical apart from that list. The listing is
    substituted rather than interpolated, since the cell's own f-strings would
    otherwise be swallowed by an outer f-string.
    """
    listing = "".join(f'    "{name}",\n' for name in checked)
    return _code(
        '''
import importlib

# Dependency order: a module is reloaded only after everything it imports.
CHECKED = (
__CHECKED__
)


def loaded_revisions():
    revisions = {}
    for name in CHECKED:
        module = importlib.import_module(name)
        revisions[name] = getattr(module, "NOTEBOOK_SOURCE_REVISION", None)
    return revisions


def describe(name, revision):
    if revision is None:
        return f"  {name}: imported before this notebook revision existed"
    return f"  {name}: {revision} (expected {EXPECTED_SOURCE_REVISION})"


def reload_stale(revisions):
    """Re-execute the mismatched modules so this session picks up the new code.

    Reloading works here because nothing has been built yet: the source cell only
    writes files, and this cell runs before any model, image or result exists, so
    there is no object still holding a reference to the old classes.
    """
    for name in CHECKED:
        if revisions.get(name) == EXPECTED_SOURCE_REVISION:
            continue
        try:
            importlib.reload(importlib.import_module(name))
        except Exception as error:
            raise RuntimeError(
                f"Fix this first: Runtime > Restart session, then Run all.\\n"
                f"Reloading {name} failed ({type(error).__name__}: {error})."
            ) from error


revisions = loaded_revisions()
stale = {name: revision for name, revision in revisions.items() if revision != EXPECTED_SOURCE_REVISION}
if stale:
    print("stale modules in this session:")
    for name, revision in stale.items():
        print(describe(name, revision))
    reload_stale(revisions)
    revisions = loaded_revisions()
    still_stale = {name: revision for name, revision in revisions.items()
                   if revision != EXPECTED_SOURCE_REVISION}
    if still_stale:
        raise RuntimeError(
            "Fix this first: Runtime > Restart session, then Run all.\\n"
            "This session still runs different code than the cell above wrote:\\n"
            + "\\n".join(describe(name, revision) for name, revision in still_stale.items())
        )
    print(f"reloaded {len(stale)} stale module(s); the session now matches the source")

print(f"loaded modules match the embedded source (revision {EXPECTED_SOURCE_REVISION})")
'''
        .replace("__CHECKED__", listing)
    )


